inline const char *Tr(const char *text) {
    if (!text || !*text || current == Lang::ZhCN)
        return text ? text : "";
    const auto &table = current == Lang::En ? English() : Traditional();
    auto it = table.find(std::string_view(text));
    return it == table.end() ? text : it->second;
}
